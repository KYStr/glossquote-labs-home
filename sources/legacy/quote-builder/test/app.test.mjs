import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { mountQuoteApp, messages } from '../public/js/app.js';
import { documentFixture } from './dom-fixture.mjs';

for (const [lang, file] of [['zh-Hant', 'index.html'], ['en', 'en/index.html']]) {
  test(`${lang}: actual page/controller wiring; errors, add/remove, text preview, stale, confirmed clear and pagehide (offline fixture only)`, async () => {
    const { doc, win } = documentFixture(await readFile(new URL(`../public/${file}`, import.meta.url), 'utf8'));
    const session = mountQuoteApp(doc, win);
    const get = id => doc.getElementById(id);
    assert.equal(session.state.phase, 'blank');
    assert.equal(get('item-list').children.length, 1);
    assert.equal(get('downloads').hidden, true);
    get('quote-form').dispatch('submit');
    assert.equal(session.state.phase, 'error');
    assert.equal(get('items-0-description').getAttribute('aria-invalid'), 'true');
    assert.equal(doc.activeElement.id, 'items-0-description');
    const danger = '</td><script>alert(1)</script>&"\'';
    get('items-0-description').value = danger;
    get('items-0-quantity').value = '2.5'; get('items-0-unitPrice').value = '19.99';
    get('quote-form').dispatch('input');
    get('add-item').dispatch('click');
    assert.equal(doc.activeElement.id, 'items-1-description');
    get('items-1-description').value = 'Second'; get('items-1-quantity').value = '1'; get('items-1-unitPrice').value = '10';
    get('discount').value = '9.98'; get('taxRate').value = '5'; get('note').value = 'END:VCARD\r\n<img onerror=x>';
    get('quote-form').dispatch('submit');
    assert.equal(session.state.phase, 'ready');
    assert.equal(get('workspace').dataset.panel, 'preview');
    assert.equal(doc.activeElement.id, 'preview-heading');
    assert.ok(get('quote-canvas').textContent.includes(danger));
    assert.ok(get('quote-canvas').textContent.includes('TWD 52.50'));
    assert.equal(doc.createdTags.includes('script'), false);
    assert.equal(doc.createdTags.includes('img'), false);
    assert.equal(get('downloads').hidden, false);
    assert.equal(get('download-html').getAttribute('href'), '#', 'ready link is keyboard-addressable');
    get('items-0-unitPrice').value = 'invalid'; get('quote-form').dispatch('input');
    assert.equal(get('downloads').hidden, true);
    assert.equal(get('download-html').getAttribute('href'), null);
    assert.equal(get('quote-canvas').textContent.includes('52.50'), false);
    assert.equal(get('draft-state').textContent, messages[lang].stale);
    get('tab-edit').dispatch('click');
    get('clear-draft').dispatch('click'); get('cancel-clear').dispatch('click');
    assert.equal(get('items-0-description').value, danger);
    get('clear-draft').dispatch('click'); get('confirm-clear').dispatch('click');
    assert.equal(session.state.phase, 'blank');
    assert.equal(get('items-0-description').value, '');
    assert.equal(get('item-list').children.length, 1);
    get('add-item').dispatch('click');
    get('items-0-description').value = 'First'; get('items-1-description').value = 'Keep this';
    const removeFirst = get('item-list').children[0].querySelectorAll('button')[0]; removeFirst.dispatch('click');
    assert.equal(get('items-0-description').value, 'Keep this');
    assert.equal(get('item-list').children.length, 1);
    win.dispatch('pagehide');
    assert.equal(session.state.draft, null);
    assert.equal(get('item-list').children.length, 0);
    for (const control of get('quote-form').querySelectorAll('input,textarea')) assert.equal(control.value, '');
    win.dispatch('pageshow');
    assert.equal(session.state.phase, 'blank');
    assert.equal(get('item-list').children.length, 1);
    assert.equal(get('from').value, '');
  });
}
test('all fixed error codes have nonempty Chinese and English recovery messages', () => {
  assert.deepEqual(Object.keys(messages.en.errors).sort(), Object.keys(messages['zh-Hant'].errors).sort());
  for (const dictionary of Object.values(messages)) for (const value of Object.values(dictionary.errors)) assert.ok(typeof value === 'string' && value.trim().length > 0);
  assert.ok(messages.en.importSummary(2).includes('12 editable fields'));
  assert.ok(messages['zh-Hant'].importSummary(2).includes('12 個可編輯欄位'));
});
