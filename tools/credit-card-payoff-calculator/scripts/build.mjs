import { copyFile, lstat, mkdir, readdir, readFile, realpath, rm } from "node:fs/promises";
import { dirname, extname, isAbsolute, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { runProjectCheck } from "./check.mjs";

const PROJECT_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const ALLOWED_EXTENSIONS = new Set([".html", ".css", ".js", ".mjs"]);
const CORE_RELATIVE = "public/js/core/payoff.mjs";
const WORKER_SOURCE_RELATIVE = "js/worker-source.mjs";

// The fixed message handler appended to the embedded core inside the
// Worker. It only ever calls the pure core `run` and posts the outcome
// back with the generation it was given.
const WORKER_HANDLER = `
self.onmessage = (event) => {
  const data = event ? event.data : null;
  let outcome;
  try {
    outcome = run(data ? data.input : null);
  } catch {
    outcome = { ok: false, error: { code: "INTERNAL", field: null, row: null } };
  }
  self.postMessage({ generation: data ? data.generation : null, outcome });
};
`;

// Embeds the fixed core source bytes: the module's top-level export
// markers are stripped so the code runs as a classic module body
// inside the Worker, then the fixed handler is appended. The result
// is deterministic for fixed core bytes.
export function generateWorkerSource(coreSource) {
  const stripped = coreSource.replace(/^export /gm, "");
  if (/^export /m.test(stripped)) {
    throw new Error("Core source has an export form the embedder cannot strip.");
  }
  return `${stripped}${WORKER_HANDLER}`;
}

export function renderWorkerSourceModule(coreSource) {
  const workerSource = generateWorkerSource(coreSource);
  return `// Generated by scripts/build.mjs from public/js/core/payoff.mjs.\n// Do not edit; rebuild with npm run build:preview.\nexport const WORKER_SOURCE = ${JSON.stringify(workerSource)};\n`;
}

function isPathInside(rootPath, candidatePath) {
  const difference = relative(rootPath, candidatePath);
  return difference === "" || (
    difference !== ".." &&
    !isAbsolute(difference) &&
    difference.split(sep)[0] !== ".."
  );
}

async function readPathInfo(path) {
  try {
    return await lstat(path);
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw new Error("A build path could not be inspected.");
  }
}

async function collectPublicFiles(projectRoot) {
  const publicRoot = resolve(projectRoot, "public");
  const rootInfo = await readPathInfo(publicRoot);
  if (!rootInfo || !rootInfo.isDirectory() || rootInfo.isSymbolicLink()) {
    throw new Error("The public source must be a regular directory.");
  }
  const canonicalPublic = await realpath(publicRoot);
  if (!isPathInside(projectRoot, canonicalPublic) || canonicalPublic === projectRoot) {
    throw new Error("The public source resolves outside the project.");
  }
  const files = [];
  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      const sourcePath = resolve(directory, entry.name);
      const info = await readPathInfo(sourcePath);
      if (!info) throw new Error("A public source path disappeared during build.");
      if (info.isSymbolicLink()) {
        throw new Error("Symbolic links are not allowed in public build sources.");
      }
      if (entry.name[0] === ".") {
        throw new Error("Dotfiles are not allowed in public build sources.");
      }
      if (info.isDirectory()) {
        await visit(sourcePath);
        continue;
      }
      if (!info.isFile() || !ALLOWED_EXTENSIONS.has(extname(sourcePath).toLowerCase())) {
        throw new Error("A public source file has an unsupported type.");
      }
      const canonicalSource = await realpath(sourcePath);
      if (!isPathInside(canonicalPublic, canonicalSource)) {
        throw new Error("A public source resolves outside public.");
      }
      files.push({ sourcePath: canonicalSource, relativePath: relative(publicRoot, sourcePath) });
    }
  }
  await visit(publicRoot);
  if (!files.some(({ relativePath }) => relativePath === "index.html")) {
    throw new Error("The public build must contain index.html.");
  }
  return files;
}

export async function buildPreview({ projectPath = PROJECT_ROOT, outputDir = null, check = runProjectCheck } = {}) {
  const projectRoot = await realpath(resolve(projectPath));
  const distPath = outputDir !== null ? resolve(outputDir) : resolve(projectRoot, "dist-preview");
  if (check) await check(projectRoot);

  const files = await collectPublicFiles(projectRoot);
  const existing = await readPathInfo(distPath);
  if (existing && (existing.isSymbolicLink() || !existing.isDirectory())) {
    throw new Error("The preview output cannot be a symbolic link or a non-directory.");
  }
  await rm(distPath, { recursive: true, force: true });
  await mkdir(distPath, { recursive: true });

  for (const { sourcePath, relativePath } of files) {
    const targetPath = resolve(distPath, relativePath);
    if (!isPathInside(distPath, targetPath) || targetPath === distPath) {
      throw new Error("A build output path escapes the preview directory.");
    }
    await mkdir(dirname(targetPath), { recursive: true });
    await copyFile(sourcePath, targetPath);
  }

  const coreSource = await readFile(resolve(projectRoot, CORE_RELATIVE), "utf8");
  const workerTarget = resolve(distPath, WORKER_SOURCE_RELATIVE);
  await mkdir(dirname(workerTarget), { recursive: true });
  const { writeFile } = await import("node:fs/promises");
  await writeFile(workerTarget, renderWorkerSourceModule(coreSource), "utf8");

  return { outputPath: distPath, fileCount: files.length + 1 };
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    const modeIndex = args.indexOf("--mode");
    const mode = modeIndex === -1 ? "" : args[modeIndex + 1];
    if (mode === "production") {
      throw new Error("Production output cannot exist while no site URL is approved.");
    }
    if (mode !== "preview") {
      throw new Error("Usage: node scripts/build.mjs --mode preview");
    }
    const result = await buildPreview();
    process.stdout.write(`Built ${result.fileCount} static files into dist-preview.\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "Build failed."}\n`);
    process.exitCode = 1;
  }
}
