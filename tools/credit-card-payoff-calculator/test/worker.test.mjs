import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import vm from "node:vm";

// The preview build embeds the fixed core source plus a fixed message
// handler into a Worker. This suite executes that exact embedded
// source in a vm context with a fake `self`, and confirms it answers
// with the same outcomes as the core the tests import directly.

import { run } from "../public/js/core/payoff.mjs";
import { generateWorkerSource, renderWorkerSourceModule } from "../scripts/build.mjs";

const coreSource = await readFile(
  new URL("../public/js/core/payoff.mjs", import.meta.url),
  "utf8",
);
const workerSource = generateWorkerSource(coreSource);

function makeWorkerContext() {
  const received = [];
  const self = {
    onmessage: null,
    postMessage: (message) => received.push(message),
  };
  const sandbox = { self, TextEncoder, console };
  vm.createContext(sandbox);
  vm.runInContext(workerSource, sandbox);
  return { self, received };
}

// Objects created inside the vm live in another realm, so their
// prototypes differ; compare through a JSON round trip instead.
function plain(value) {
  return JSON.parse(JSON.stringify(value));
}

test("embedded worker source answers fixture inputs like the core", () => {
  const inputs = [
    {
      balance: "1200.00", aprPercent: "12", mode: "payment",
      monthlyPayment: "110.00", targetMonths: null,
    },
    {
      balance: "10000.00", aprPercent: "24", mode: "months",
      monthlyPayment: null, targetMonths: "12",
    },
    {
      balance: "5000.00", aprPercent: "24", mode: "payment",
      monthlyPayment: "100.00", targetMonths: null,
    },
  ];
  const { self, received } = makeWorkerContext();
  assert.equal(typeof self.onmessage, "function");
  inputs.forEach((input, index) => {
    self.onmessage({ data: { generation: index + 1, input } });
  });
  assert.equal(received.length, inputs.length);
  inputs.forEach((input, index) => {
    assert.equal(received[index].generation, index + 1);
    assert.deepStrictEqual(plain(received[index].outcome), run(input));
  });
});

test("embedded worker source reports schema errors instead of throwing", () => {
  const { self, received } = makeWorkerContext();
  self.onmessage({ data: { generation: 9, input: null } });
  assert.equal(received.length, 1);
  assert.equal(received[0].generation, 9);
  assert.deepStrictEqual(plain(received[0].outcome), {
    ok: false,
    error: { code: "SCHEMA", field: null, row: null },
  });
});

test("worker source generation is deterministic", () => {
  assert.equal(generateWorkerSource(coreSource), workerSource);
  assert.equal(renderWorkerSourceModule(coreSource), renderWorkerSourceModule(coreSource));
  const moduleText = renderWorkerSourceModule(coreSource);
  assert.ok(moduleText.startsWith("// Generated by scripts/build.mjs"));
  assert.ok(moduleText.includes("export const WORKER_SOURCE = "));
});
