// Reproducible preview build for Binary Record Inspector.
// Copies public/ into dist-preview/ and generates dist-preview/js/
// worker-source.js: the fixed Worker module source, which is the pure core
// (public/js/core/inspector.mjs) concatenated with the message handler
// (src/worker-entry.mjs). The build is deterministic: no timestamps, no
// random values, files copied in sorted order.
import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'dist-preview');

const modeArg = process.argv.indexOf('--mode');
const mode = modeArg >= 0 ? process.argv[modeArg + 1] : 'preview';
if (mode !== 'preview') {
  console.error(`unknown mode: ${mode}`);
  process.exit(1);
}

function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

async function listFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(full)));
    else if (entry.isFile()) files.push(full);
  }
  return files;
}

const core = await readFile(path.join(root, 'public/js/core/inspector.mjs'), 'utf8');
const entry = await readFile(path.join(root, 'src/worker-entry.mjs'), 'utf8');
const combined = core + '\n' + entry;
const workerSource =
  '// Generated by scripts/build.mjs --mode preview. Do not edit.\n' +
  `// Embedded core sha256: ${sha256(core)}\n` +
  `// Worker entry sha256: ${sha256(entry)}\n` +
  `export const WORKER_SOURCE = ${JSON.stringify(combined)};\n`;

await rm(outDir, { recursive: true, force: true });
await mkdir(path.join(outDir, 'js'), { recursive: true });
await cp(path.join(root, 'public'), outDir, { recursive: true });
await writeFile(path.join(outDir, 'js/worker-source.js'), workerSource, 'utf8');

const built = await listFiles(outDir);
console.log(`built dist-preview (${built.length} files)`);
for (const file of built) {
  console.log(`  ${path.relative(outDir, file)}`);
}
