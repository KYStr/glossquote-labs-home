// Reproducible preview build for the Parking Fee Calculator.
// Copies public/ into dist-preview/ and generates js/worker-source.mjs:
// the fixed worker source string, assembled at build time from the pure
// core source bytes (messages + parking) plus a pinned bootstrap, exactly
// as SPEC.md requires. Deterministic: same inputs -> same output bytes.

import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const TOOL_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const PUBLIC_DIR = path.join(TOOL_DIR, "public");
const DEFAULT_OUT = path.join(TOOL_DIR, "dist-preview");

const BOOTSTRAP = [
  "",
  "self.onmessage = (event) => {",
  "  const data = event.data || {};",
  "  let outcome;",
  "  try {",
  "    outcome = run(data.input);",
  "  } catch {",
  "    outcome = { ok: false, error: { code: \"WORKER_ERROR\", field: null, row: null } };",
  "  }",
  "  self.postMessage({ generation: data.generation, outcome });",
  "};",
  ""
].join("\n");

// Strip ESM export syntax so the modules concatenate into one worker
// scope. Core files are written import-free with distinct top-level names.
function deExport(source) {
  return source
    .replace(/^export default /gm, "")
    .replace(/^export \{[^}]*\};?\s*$/gm, "")
    .replace(/^export /gm, "");
}

export async function workerSource() {
  const messages = await readFile(path.join(PUBLIC_DIR, "js/core/messages.mjs"), "utf8");
  const parking = await readFile(path.join(PUBLIC_DIR, "js/core/parking.mjs"), "utf8");
  return deExport(messages) + "\n" + deExport(parking) + "\n" + BOOTSTRAP;
}

export async function buildPreview(outDir) {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await cp(PUBLIC_DIR, outDir, { recursive: true });
  const source = await workerSource();
  const moduleText =
    "// Generated by scripts/build.mjs from the fixed core source bytes. Do not edit.\n" +
    "export const WORKER_SOURCE = " + JSON.stringify(source) + ";\n";
  await writeFile(path.join(outDir, "js/worker-source.mjs"), moduleText, "utf8");
  return outDir;
}

export async function treeDigest(root) {
  const { readdir } = await import("node:fs/promises");
  const entries = [];
  async function walk(dir, rel) {
    const items = await readdir(dir, { withFileTypes: true });
    items.sort((a, b) => (a.name < b.name ? -1 : 1));
    for (const item of items) {
      const r = rel === "" ? item.name : rel + "/" + item.name;
      if (item.isDirectory()) await walk(path.join(dir, item.name), r);
      else entries.push(r);
    }
  }
  await walk(root, "");
  const lines = [];
  for (const rel of entries) {
    const bytes = await readFile(path.join(root, rel));
    lines.push(createHash("sha256").update(bytes).digest("hex") + "  " + rel);
  }
  return lines.join("\n") + "\n";
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes("--verify")) {
    const tmp = await mkdtemp(path.join(tmpdir(), "parking-preview-"));
    try {
      const fresh = path.join(tmp, "fresh");
      await buildPreview(fresh);
      const [a, b] = [await treeDigest(fresh), await treeDigest(DEFAULT_OUT)];
      if (a !== b) {
        console.error("check:generated:preview FAIL — dist-preview differs from a fresh build");
        process.exit(1);
      }
      console.log("check:generated:preview PASS — dist-preview matches a fresh build byte for byte");
    } finally {
      await rm(tmp, { recursive: true, force: true });
    }
  } else {
    await buildPreview(DEFAULT_OUT);
    console.log("build:preview wrote " + DEFAULT_OUT);
  }
}
