// Reproducible preview build.
// Copies public/ into dist-preview/, embeds the worker source, and
// writes the path/sorted manifest. Deterministic output: sorted entries,
// fixed timestamps (1970-01-01T00:00:00.000Z), no temp paths, no randomness.

import { createHash } from "node:crypto";
import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const toolRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(toolRoot, "public");
const distDir = path.join(toolRoot, "dist-preview");
const FIXED_MTIME = new Date("1970-01-01T00:00:00.000Z");

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

await rm(distDir, { recursive: true, force: true });
await cp(publicDir, distDir, { recursive: true, preserveTimestamps: false });

// Embed the worker source as a JS module the page imports. The worker
// source is the pure core source followed by the handler fragment
// (whose only import-less references are `self` and the core's `run`).
const coreSource = await readFile(path.join(publicDir, "js/core/video-size.mjs"), "utf8");
const handlerSource = await readFile(path.join(publicDir, "js/worker-handler.mjs"), "utf8");
const workerSource = [coreSource, handlerSource].join("\n// ---- worker handler ----\n");
const workerModule = `// Generated by scripts/build.mjs. Fixed worker source embedded for the preview.\nexport const WORKER_SOURCE = ${JSON.stringify(workerSource)};\n`;
await writeFile(path.join(distDir, "js/worker-source.js"), workerModule);

const { readdir, stat } = await import("node:fs/promises");
async function listFiles(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (entry.isDirectory()) files.push(...(await listFiles(path.join(dir, entry.name), `${prefix}${entry.name}/`)));
    else files.push(`${prefix}${entry.name}`);
  }
  return files;
}

const fileEntries = [];
for (const relative of await listFiles(distDir)) {
  const bytes = await readFile(path.join(distDir, relative));
  const info = await stat(path.join(distDir, relative));
  fileEntries.push({
    path: relative,
    bytes: bytes.byteLength,
    sha256: sha256(bytes),
    mtime: FIXED_MTIME.toISOString(),
    mode: "0644",
    size: info.size,
  });
}

const manifest = { generatedBy: "scripts/build.mjs", files: fileEntries };
await writeFile(
  path.join(toolRoot, "BUILD-MANIFEST.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

console.log(`built dist-preview with ${fileEntries.length} files`);
console.log(`worker source sha256: ${sha256(Buffer.from(workerSource, "utf8"))}`);
