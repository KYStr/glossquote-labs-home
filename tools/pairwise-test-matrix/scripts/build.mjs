// Reproducible preview build.
// 1. Regenerate public/js/worker-source.mjs from the fixed core source
//    bytes plus the fixed worker entry (deterministic; no timestamps).
// 2. Copy public/ into dist-preview/.
// With --check, rebuild into a temporary directory and verify that
// dist-preview/ and the committed worker-source.mjs match it byte for
// byte, without writing anything.

import { cp, mkdtemp, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { WORKER_ENTRY } from './worker-entry.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const PUBLIC = join(ROOT, 'public');
const DIST = join(ROOT, 'dist-preview');
const CORE = join(PUBLIC, 'js', 'core', 'pairwise.mjs');
const WORKER_SOURCE_FILE = join(PUBLIC, 'js', 'worker-source.mjs');

export async function workerSourceText() {
  const core = await readFile(CORE, 'utf8');
  const source = `${core}${WORKER_ENTRY}`;
  return `// Generated by scripts/build.mjs from public/js/core/pairwise.mjs\n// plus scripts/worker-entry.mjs. Do not edit by hand.\nexport const WORKER_SOURCE = ${JSON.stringify(source)};\n`;
}

async function listFiles(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const out = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(path, base)));
    else if (entry.isFile()) out.push(relative(base, path));
  }
  return out;
}

async function hashTree(dir) {
  const files = await listFiles(dir);
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file);
    hash.update('\0');
    hash.update(await readFile(join(dir, file)));
    hash.update('\0');
  }
  return { files, hash: hash.digest('hex') };
}

async function buildInto(target) {
  await rm(target, { recursive: true, force: true });
  await cp(PUBLIC, target, { recursive: true });
}

async function main() {
  const check = process.argv.includes('--check');
  const generated = await workerSourceText();
  if (check) {
    const committed = await readFile(WORKER_SOURCE_FILE, 'utf8');
    if (committed !== generated) {
      console.error('worker-source.mjs is out of sync with the core source; run node scripts/build.mjs');
      process.exit(1);
    }
    const tmp = await mkdtemp(join(tmpdir(), 'pairwise-preview-'));
    try {
      await buildInto(tmp);
      const want = await hashTree(tmp);
      const got = await hashTree(DIST);
      if (want.hash !== got.hash) {
        console.error(`dist-preview/ does not match a fresh build (fresh ${want.hash}, on disk ${got.hash})`);
        process.exit(1);
      }
      console.log(`check:generated:preview ok (${want.files.length} files, sha256 ${want.hash})`);
    } finally {
      await rm(tmp, { recursive: true, force: true });
    }
    return;
  }
  await writeFile(WORKER_SOURCE_FILE, generated, 'utf8');
  await buildInto(DIST);
  const { files, hash } = await hashTree(DIST);
  console.log(`build:preview ok (${files.length} files, sha256 ${hash})`);
}

await main();
