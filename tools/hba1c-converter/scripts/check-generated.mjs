#!/usr/bin/env node
// Checks the generated preview output (dist-preview/).
// Usage: node scripts/check-generated.mjs --mode preview
// Verifies: BUILD-MANIFEST.json matches dist-preview/ exactly (same set,
// same byte counts, same SHA-256), both generated pages carry the preview
// metadata (noindex, language, title, description, h1, no
// canonical/hreflang), the embedded worker source equals the fixed core +
// handler bytes, and robots.txt denies all. Exit 0 = pass.

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIST_ROOT = resolve(PROJECT_ROOT, 'dist-preview');

const modeArg = process.argv.find((arg) => arg.startsWith('--mode'));
const mode = modeArg ? process.argv[process.argv.indexOf(modeArg) + 1] ?? modeArg.split('=')[1] : undefined;
if (mode !== 'preview') {
  throw new Error('Only --mode preview is supported; production origin is not approved.');
}

async function collectFiles(directory, base = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(fullPath, base)));
    else files.push(relative(base, fullPath).split(sep).join('/'));
  }
  return files.sort();
}

const manifest = JSON.parse(await readFile(resolve(PROJECT_ROOT, 'BUILD-MANIFEST.json'), 'utf8'));
assert.equal(manifest.mode, 'preview');
const onDisk = await collectFiles(DIST_ROOT);
assert.deepEqual(
  onDisk,
  manifest.files.map((file) => file.path).sort(),
  'dist-preview/ file set differs from BUILD-MANIFEST.json',
);
for (const file of manifest.files) {
  const bytes = await readFile(resolve(DIST_ROOT, file.path));
  assert.equal(bytes.length, file.bytes, `${file.path}: byte count`);
  assert.equal(
    createHash('sha256').update(bytes).digest('hex'),
    file.sha256,
    `${file.path}: sha256`,
  );
}
console.log(`ok: dist-preview matches BUILD-MANIFEST.json (${manifest.files.length} files)`);

const expectations = [
  ['index.html', 'zh-Hant', '糖化血色素換算'],
  ['en/index.html', 'en', 'HbA1c Converter'],
];
for (const [path, lang, h1] of expectations) {
  const html = await readFile(resolve(DIST_ROOT, path), 'utf8');
  assert.ok(html.includes('<meta name="robots" content="noindex,nofollow">'), `${path}: noindex`);
  assert.ok(html.includes(`<html lang="${lang}">`), `${path}: lang=${lang}`);
  assert.ok(html.includes(`<h1>${h1}</h1>`), `${path}: h1`);
  assert.ok(!/rel="canonical"/.test(html), `${path}: no canonical`);
  assert.ok(!/rel="alternate"/.test(html), `${path}: no hreflang`);
}
console.log('ok: generated pages carry preview metadata');

// The embedded worker source must be exactly core + handler bytes.
const coreSource = await readFile(resolve(PROJECT_ROOT, 'public/js/core/convert.mjs'), 'utf8');
const handlerSource = await readFile(resolve(PROJECT_ROOT, 'public/js/worker-handler.mjs'), 'utf8');
const workerSource = await readFile(resolve(DIST_ROOT, 'js/worker-source.js'), 'utf8');
const expectedWorker = `// Generated by scripts/build.mjs --mode preview from the fixed source\n// bytes of public/js/core/convert.mjs and public/js/worker-handler.mjs.\n// Do not edit by hand; rebuild to regenerate.\nexport const WORKER_SOURCE = ${JSON.stringify(`${coreSource}\n${handlerSource}`)};\n`;
assert.equal(workerSource, expectedWorker, 'js/worker-source.js differs from fixed core + handler bytes');
console.log('ok: embedded worker source equals fixed core + handler bytes');

const robots = await readFile(resolve(DIST_ROOT, 'robots.txt'), 'utf8');
assert.equal(robots, 'User-agent: *\nDisallow: /\n', 'robots.txt must deny all');
console.log('ok: robots.txt denies all');

console.log('all generated-output checks passed');
