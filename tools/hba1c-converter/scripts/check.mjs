#!/usr/bin/env node
// Static checks for the HbA1c Converter (source tree).
// Usage: node scripts/check.mjs
// Verifies the package contract, required files, core purity, forbidden
// sinks, preview CSP/robots metadata, bilingual id parity, the pinned
// SPEC strings, the pinned ADAG/IFCC formulas (via the literal 7% fixture
// and the canonical report bytes), the ADA category table, and i18n key
// parity. Exit 0 = pass.

import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MESSAGES } from '../public/js/i18n.mjs';
import { run, serializeReport } from '../public/js/core/convert.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const failures = [];

function fail(messageText) {
  failures.push(messageText);
  console.error(`FAIL: ${messageText}`);
}

function pass(messageText) {
  console.log(`ok: ${messageText}`);
}

async function exists(relative) {
  try {
    await stat(path.join(root, relative));
    return true;
  } catch {
    return false;
  }
}

async function read(relative) {
  return readFile(path.join(root, relative), 'utf8');
}

const REQUIRED_FILES = [
  'package.json',
  'public/index.html',
  'public/en/index.html',
  'public/js/app.js',
  'public/js/controller.mjs',
  'public/js/i18n.mjs',
  'public/js/worker-handler.mjs',
  'public/js/core/convert.mjs',
  'public/styles/app.css',
  'scripts/build.mjs',
  'scripts/check.mjs',
  'scripts/check-generated.mjs',
  'scripts/serve.mjs',
  'test/core.test.mjs',
  'test/controller.test.mjs',
  'test/html.test.mjs',
  'test/report.test.mjs',
  'test/build.test.mjs',
  'test/fixtures.mjs',
  'HANDOFF.md',
  'VERIFICATION.md',
];

const REQUIRED_IDS = [
  'value-input', 'unit-select',
  'run-button', 'example-button', 'reset-button', 'cancel-button', 'download-button',
  'status', 'status-text', 'error-box', 'error-text', 'example-note', 'value-help',
  'result-section', 'result-summary',
  'res-a1c', 'res-ifcc', 'res-eag-mgdl', 'res-eag-mmoll', 'res-category',
  'disclaimer', 'category-table',
];

// Forbidden anywhere in public/js: dynamic execution, network, storage,
// clipboard, console output, markup sinks.
const FORBIDDEN_JS = [
  'innerHTML', 'outerHTML', 'document.write', 'eval(', 'new Function',
  'fetch(', 'XMLHttpRequest', 'WebSocket', 'sendBeacon',
  'localStorage', 'sessionStorage', 'indexedDB', 'clipboard',
  'console.',
];

const CSP = "default-src 'none'; script-src 'self'; style-src 'self'; worker-src 'blob:'; img-src 'self'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";

const DISCLAIMER = '本工具僅提供估算與單位換算，不構成醫療建議或診斷。請與醫師討論你的檢查結果。 / This tool provides estimates and unit conversions only. It is not medical advice or a diagnosis. Discuss your results with your clinician.';

async function main() {
  // Package contract.
  const pkg = JSON.parse(await read('package.json'));
  if (pkg.type !== 'module') fail('package.json: type must be "module"');
  if (!/^>=24/.test(pkg.engines?.node ?? '')) fail('package.json: engines.node must be >=24');
  if (pkg.dependencies !== undefined || pkg.devDependencies !== undefined) {
    fail('package.json: no runtime or dev dependencies allowed');
  }
  for (const script of ['test', 'check', 'build:preview', 'check:generated:preview']) {
    if (typeof pkg.scripts?.[script] !== 'string') fail(`package.json: missing script "${script}"`);
  }
  pass('package contract');

  // Required files.
  for (const file of REQUIRED_FILES) {
    if (!(await exists(file))) fail(`missing file: ${file}`);
  }
  pass('required files present');

  // worker-source.js is generated by the build; it must not be hand-kept
  // in public/ (the app import resolves against dist-preview/).
  if (await exists('public/js/worker-source.js')) {
    fail('public/js/worker-source.js must not exist; it is generated by the build');
  }
  pass('no hand-kept worker-source in public/');

  // Core purity: no imports, no DOM/network/storage globals.
  const core = await read('public/js/core/convert.mjs');
  if (/^\s*import\s/m.test(core) || /\bfrom\s+['"]/.test(core)) {
    fail('core: must not import anything');
  }
  for (const token of ['document', 'window', 'navigator', 'fetch(', 'localStorage', 'XMLHttpRequest']) {
    if (core.includes(token)) fail(`core: forbidden token ${token}`);
  }
  pass('core purity');

  // Forbidden sinks in all public/js files.
  const jsFiles = [
    'public/js/app.js',
    'public/js/controller.mjs',
    'public/js/i18n.mjs',
    'public/js/worker-handler.mjs',
    'public/js/core/convert.mjs',
  ];
  for (const file of jsFiles) {
    const text = await read(file);
    for (const token of FORBIDDEN_JS) {
      if (text.includes(token)) fail(`${file}: forbidden token ${token}`);
    }
    if (/import\(/.test(text)) fail(`${file}: dynamic import is not allowed`);
  }
  pass('no forbidden sinks in public/js');

  // Pinned formulas, checked against the literal SPEC fixture for A1c 7%
  // (not against values derived from this implementation anywhere else).
  const seven = run({ value: '7', unit: 'a1c-percent' });
  const sevenExpected = {
    ok: true,
    result: {
      a1cPercent: '7.00', ifcc: '53', eagMgdl: '154', eagMmoll: '8.6', category: 'diabetes-range',
    },
  };
  if (JSON.stringify(seven) !== JSON.stringify(sevenExpected)) {
    fail(`pinned 7% fixture mismatch: ${JSON.stringify(seven)}`);
  }
  const report = serializeReport(sevenExpected.result);
  if (!report.ok || report.text !== '{"a1cPercent":"7.00","category":"diabetes-range","eagMgdl":"154","eagMmoll":"8.6","ifcc":"53"}\n') {
    fail('pinned 7% report bytes mismatch');
  }
  pass('pinned ADAG/IFCC formulas (7% fixture) and canonical report bytes');

  // HTML checks for both languages.
  const zh = await read('public/index.html');
  const en = await read('public/en/index.html');
  let zhIds = null;
  for (const [name, html] of [['zh', zh], ['en', en]]) {
    if (!html.includes('<meta name="robots" content="noindex,nofollow">')) {
      fail(`${name}: missing robots noindex,nofollow meta`);
    }
    if (!html.includes(`content="${CSP}"`)) fail(`${name}: missing or wrong CSP meta`);
    if (/rel="canonical"/.test(html) || /rel="alternate"/.test(html)) {
      fail(`${name}: preview must not carry canonical/hreflang links`);
    }
    if (/href="https?:\/\//.test(html) || /src="https?:\/\//.test(html)) {
      fail(`${name}: external http(s) URL referenced`);
    }
    if (/<script(?![^>]*\bsrc=)/.test(html)) fail(`${name}: inline script found`);
    if (/\son\w+\s*=/.test(html)) fail(`${name}: inline event handler found`);
    for (const id of REQUIRED_IDS) {
      if (!html.includes(`id="${id}"`)) fail(`${name}: missing id="${id}"`);
    }
    const ids = new Set([...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]));
    if (name === 'zh') zhIds = ids;
    else {
      const missing = [...zhIds].filter((id) => !ids.has(id));
      const extra = [...ids].filter((id) => !zhIds.has(id));
      if (missing.length > 0) fail(`en: ids missing vs zh: ${missing.join(', ')}`);
      if (extra.length > 0) fail(`en: extra ids vs zh: ${extra.join(', ')}`);
    }
    // The verbatim disclaimer (zh/en) appears in the result section.
    if (!html.includes(DISCLAIMER)) fail(`${name}: verbatim disclaimer missing`);
    // ADA category table rows.
    for (const row of ['<td>&lt; 5.7%</td>', '<td>5.7–6.4%</td>', '<td>≥ 6.5%</td>']) {
      if (!html.includes(row)) fail(`${name}: category table row missing: ${row}`);
    }
  }
  pass('HTML metadata, id parity, disclaimer and category table');

  // Exact SPEC strings.
  if (!zh.includes('<html lang="zh-Hant">')) fail('zh: lang must be zh-Hant');
  if (!zh.includes('<title>糖化血色素換算｜Gloss Tools</title>')) fail('zh: title mismatch');
  if (!zh.includes('<h1>糖化血色素換算</h1>')) fail('zh: h1 mismatch');
  if (!zh.includes('輸入 HbA1c 或平均血糖的一個數值，一次對照 %、mmol/mol、mg/dL、mmol/L 四種表示法與 ADA 分級帶。')) {
    fail('zh: description mismatch');
  }
  if (!en.includes('<html lang="en">')) fail('en: lang must be en');
  if (!en.includes('<title>HbA1c Converter | Gloss Tools</title>')) fail('en: title mismatch');
  if (!en.includes('<h1>HbA1c Converter</h1>')) fail('en: h1 mismatch');
  if (!en.includes('Enter one HbA1c or average glucose value and see it in %, mmol/mol, mg/dL and mmol/L with the ADA category.')) {
    fail('en: description mismatch');
  }
  if (!zh.includes('eAG 是實測平均血糖嗎？') || !zh.includes('為什麼 mmol/L 有時和 ADA 表格差 0.1？')
    || !zh.includes('目標 A1c 是多少？') || !zh.includes('可以用這個結果診斷糖尿病嗎？')) {
    fail('zh: FAQ questions missing');
  }
  if (!en.includes('Is eAG a measured average glucose?') || !en.includes('Why does mmol/L sometimes differ from the ADA table by 0.1?')
    || !en.includes('What A1c should I aim for?') || !en.includes('Can this diagnose diabetes?')) {
    fail('en: FAQ questions missing');
  }
  if (MESSAGES['zh-Hant'].statusDirty !== '輸入已變更，請重新執行'
    || MESSAGES['zh-Hant'].statusCancelled !== '已取消，可重新執行'
    || MESSAGES.en.statusDirty !== 'Input changed. Run again.'
    || MESSAGES.en.statusCancelled !== 'Cancelled. You can run again.') {
    fail('i18n: pinned status strings mismatch');
  }
  pass('SPEC title/description/FAQ strings');

  // i18n key parity.
  const zhKeys = Object.keys(MESSAGES['zh-Hant']).sort();
  const enKeys = Object.keys(MESSAGES.en).sort();
  if (JSON.stringify(zhKeys) !== JSON.stringify(enKeys)) {
    fail(`i18n key mismatch: zh-only=${zhKeys.filter((k) => !enKeys.includes(k))} en-only=${enKeys.filter((k) => !zhKeys.includes(k))}`);
  }
  pass('i18n key parity');

  if (failures.length > 0) {
    console.error(`${failures.length} check(s) failed`);
    process.exit(1);
  }
  console.log('all static checks passed');
}

main().catch((error) => {
  console.error(`check failed: ${error.message}`);
  process.exit(1);
});
