// Static checks for the Zodiac Sign Finder. No network access.
// Verifies: package contract, JS syntax, forbidden capabilities in the
// shipped sources, HTML bilingual/metadata contract, the CSP string in
// serve.mjs against the SPEC, and that the committed worker-source file
// matches what scripts/build.mjs would generate from the current core.

import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import { extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { buildWorkerSource } from "./build.mjs";

const execFileAsync = promisify(execFile);
const PROJECT_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const PUBLIC_ROOT = resolve(PROJECT_ROOT, "public");

const failures = [];
function check(condition, message) {
  if (!condition) failures.push(message);
}

async function collect(directory, extensions) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = resolve(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await collect(full, extensions)));
    else if (extensions.has(extname(entry.name))) found.push(full);
  }
  return found.sort();
}

// 1. Package contract.
const packageJson = JSON.parse(await readFile(resolve(PROJECT_ROOT, "package.json"), "utf8"));
check(packageJson.type === "module", "package.json must set type module");
check(packageJson.private === true, "package.json must be private");
check(
  typeof packageJson.engines?.node === "string" && packageJson.engines.node.includes("24"),
  "package.json must require Node >=24",
);
check(
  !packageJson.dependencies || Object.keys(packageJson.dependencies).length === 0,
  "zero runtime dependencies required",
);
for (const script of ["test", "check", "build:preview", "check:generated:preview"]) {
  check(typeof packageJson.scripts?.[script] === "string", `missing script: ${script}`);
}

// 2. Syntax check every shipped and test JS file.
const jsFiles = [
  ...(await collect(resolve(PROJECT_ROOT, "public"), new Set([".js", ".mjs"]))),
  ...(await collect(resolve(PROJECT_ROOT, "scripts"), new Set([".js", ".mjs"]))),
  ...(await collect(resolve(PROJECT_ROOT, "test"), new Set([".js", ".mjs"]))),
];
for (const file of jsFiles) {
  try {
    await execFileAsync(process.execPath, ["--check", file]);
  } catch {
    failures.push(`syntax error: ${file}`);
  }
}

// 3. Forbidden capabilities in shipped sources (public/ only).
const FORBIDDEN = [
  ["fetch(", "fetch"],
  ["XMLHttpRequest", "XHR"],
  ["WebSocket", "WebSocket"],
  ["sendBeacon", "beacon"],
  ["eval(", "eval"],
  ["new Function", "new Function"],
  ["innerHTML", "innerHTML"],
  ["document.write", "document.write"],
  ["localStorage", "localStorage"],
  ["sessionStorage", "sessionStorage"],
  ["indexedDB", "indexedDB"],
  ["document.cookie", "cookie"],
  ["import(", "dynamic import"],
  ["http://", "absolute http URL"],
  ["https://", "absolute https URL"],
  ["//cdn", "CDN reference"],
  ["data:", "data: URL in shipped source"],
];
const publicJs = await collect(PUBLIC_ROOT, new Set([".js", ".mjs"]));
for (const file of publicJs) {
  const text = await readFile(file, "utf8");
  for (const [pattern, label] of FORBIDDEN) {
    // The worker-source file embeds the core, which is also scanned as a
    // file of its own; the generated string literal is allowed to contain
    // the core text, so only flag patterns outside the JSON string.
    if (file.endsWith("worker-source.mjs")) continue;
    check(!text.includes(pattern), `${label} forbidden in ${file}`);
  }
}
// worker-source.mjs itself must only be the generated module.
{
  const text = await readFile(resolve(PUBLIC_ROOT, "js/worker-source.mjs"), "utf8");
  check(text.startsWith("// GENERATED by scripts/build.mjs"), "worker-source.mjs must be generated");
  check(!text.includes("fetch("), "worker-source.mjs must not contain fetch");
}

// 4. Core purity: no imports at all in public/js/core/.
const coreFiles = await collect(resolve(PUBLIC_ROOT, "js/core"), new Set([".mjs"]));
check(coreFiles.length > 0, "core directory must contain modules");
for (const file of coreFiles) {
  const text = await readFile(file, "utf8");
  check(!/^import /m.test(text) && !text.includes("from \""), `core must not import: ${file}`);
}

// 5. HTML contract for both language pages. The SPEC's candidate rule
// forbids production canonical/hreflang markup in the preview: both
// must be ABSENT here.
const EXPECTED = {
  "index.html": {
    lang: "zh-Hant",
    title: "西洋星座查詢｜Gloss Tools",
    description:
      "輸入出生月日，依固定的熱帶黃道日期表查出西洋星座、符號、元素與模式；交界首末日附提示，年份選填只驗證日期存在、不影響結果。",
    h1: "西洋星座查詢",
    homeHref: "../../",
    otherHref: "en/index.html",
  },
  "en/index.html": {
    lang: "en",
    title: "Zodiac Sign Finder | Gloss Tools",
    description:
      "Enter a birth month and day to look up the Western zodiac sign, symbol, element and modality in a fixed tropical date table. Cusp days are flagged, and the optional year only validates that the date exists — it never changes the sign.",
    h1: "Zodiac Sign Finder",
    homeHref: "../../en/",
    otherHref: "../index.html",
  },
};
for (const [relativePath, expected] of Object.entries(EXPECTED)) {
  const html = await readFile(resolve(PUBLIC_ROOT, relativePath), "utf8");
  const label = `HTML ${relativePath}`;
  check(html.includes(`<html lang="${expected.lang}">`), `${label}: lang`);
  check(html.includes(`<title>${expected.title}</title>`), `${label}: title`);
  check(
    html.includes(`<meta name="description" content="${expected.description}">`),
    `${label}: description`,
  );
  check(html.includes(`<h1>${expected.h1}</h1>`), `${label}: h1`);
  check(html.includes('content="noindex, nofollow"'), `${label}: robots noindex`);
  check(!html.includes('<link rel="canonical"'), `${label}: no canonical in candidate`);
  check(!html.includes("hreflang"), `${label}: no hreflang in candidate`);
  check(html.includes(`href="${expected.homeHref}"`), `${label}: home link`);
  check(html.includes(`href="${expected.otherHref}"`), `${label}: language link`);
  check(html.includes('for="month-input"'), `${label}: month label`);
  check(html.includes('for="day-input"'), `${label}: day label`);
  check(html.includes('for="year-input"'), `${label}: year label`);
  check(!/ on\w+=/i.test(html), `${label}: no inline event handlers`);
  check(!html.includes("http://") && !html.includes("https://"), `${label}: no absolute URLs`);
  const scripts = [...html.matchAll(/<script[^>]*src="([^"]+)"/g)].map((m) => m[1]);
  check(
    scripts.length === 1 && !scripts[0].startsWith("http"),
    `${label}: exactly one local script`,
  );
  const styles = [...html.matchAll(/<link[^>]*href="([^"]+\.css)"/g)].map((m) => m[1]);
  check(styles.length === 1 && !styles[0].startsWith("http"), `${label}: exactly one local stylesheet`);
}

// 6. CSP in serve.mjs matches the SPEC exactly.
const serveText = await readFile(resolve(PROJECT_ROOT, "scripts/serve.mjs"), "utf8");
const expectedCsp =
  "default-src 'none'; script-src 'self'; style-src 'self'; worker-src blob:; img-src 'self'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";
check(serveText.includes(expectedCsp), "serve.mjs CSP must match the SPEC exactly");

// 7. Worker source consistency: regenerate and compare.
const coreSource = await readFile(resolve(PUBLIC_ROOT, "js/core/zodiac.mjs"), "utf8");
const { file: expectedWorkerFile, sha256 } = buildWorkerSource(coreSource);
const actualWorkerFile = await readFile(resolve(PUBLIC_ROOT, "js/worker-source.mjs"), "utf8");
check(actualWorkerFile === expectedWorkerFile, "worker-source.mjs is stale: run npm run build:preview");
check(
  actualWorkerFile.includes(`WORKER_SOURCE_SHA256 = ${JSON.stringify(sha256)}`),
  "worker-source.mjs must carry its SHA-256",
);
check(
  actualWorkerFile.includes(JSON.stringify(coreSource).slice(1, 200)),
  "worker-source.mjs must embed the core source verbatim",
);

// 8. CSS: no remote imports.
const cssFiles = await collect(resolve(PUBLIC_ROOT, "styles"), new Set([".css"]));
check(cssFiles.length > 0, "at least one stylesheet is required");
for (const file of cssFiles) {
  const text = await readFile(file, "utf8");
  check(!text.includes("@import"), `no @import in ${file}`);
  check(!text.includes("http://") && !text.includes("https://"), `no remote URLs in ${file}`);
}

if (failures.length > 0) {
  console.error(`check failed (${failures.length}):`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
console.log(`check ok: ${jsFiles.length} JS files, ${Object.keys(EXPECTED).length} HTML pages`);
