export function pickStrings(lang) {
  return lang === 'en' ? STRINGS.en : STRINGS['zh-Hant'];
}

export function format(template, values) {
  return template.replace(/\{(\w+)\}/g, (_match, key) =>
    (values && key in values ? String(values[key]) : `{${key}}`));
}
