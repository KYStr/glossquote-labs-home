// Static checks for the tool sources (default) or, with --generated, for the
// dist-preview/ build output against its manifest and the public/ sources.
// Exits non-zero on the first failing category and prints a summary.
import { access, readFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const generated = process.argv.includes("--generated");
const failures = [];
const check = (ok, label) => {
  console.log(`${ok ? "PASS" : "FAIL"} ${label}`);
  if (!ok) failures.push(label);
};

async function listFiles(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  const files = [];
  for (const entry of entries) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(full, base)));
    else if (entry.isFile()) files.push(relative(base, full).split("\\").join("/"));
  }
  return files;
}

if (!generated) {
  const required = [
    "package.json",
    "public/index.html",
    "public/en/index.html",
    "public/js/app.js",
    "public/js/core/prng.mjs",
    "public/js/core/pools.mjs",
    "public/js/core/generate.mjs",
    "public/styles/app.css",
    "scripts/build.mjs",
    "scripts/check.mjs",
    "scripts/serve.mjs",
    "test/prng.test.mjs",
    "test/pools.test.mjs",
    "test/generate.test.mjs",
    "HANDOFF.md",
    "VERIFICATION.md",
  ];
  for (const rel of required) {
    let ok = true;
    try {
      await access(resolve(ROOT, rel));
    } catch {
      ok = false;
    }
    check(ok, `exists: ${rel}`);
  }

  const pkg = JSON.parse(await readFile(resolve(ROOT, "package.json"), "utf8"));
  check(pkg.type === "module", "package.json is ESM");
  check(
    !pkg.dependencies || Object.keys(pkg.dependencies).length === 0,
    "package.json has zero runtime dependencies",
  );
  for (const script of ["test", "check", "build:preview", "check:generated:preview"]) {
    check(typeof pkg.scripts?.[script] === "string", `script present: ${script}`);
  }

  const coreFiles = ["prng.mjs", "pools.mjs", "generate.mjs"];
  for (const name of coreFiles) {
    const src = await readFile(resolve(ROOT, "public/js/core", name), "utf8");
    check(
      !/\b(document|window|localStorage|sessionStorage|fetch|XMLHttpRequest)\b/.test(src),
      `core/${name}: no DOM/network/storage references`,
    );
  }
  const prng = await readFile(resolve(ROOT, "public/js/core/prng.mjs"), "utf8");
  check(
    (prng.match(/0x6d2b79f5/gi) || []).length === 1,
    "PRNG constant 0x6D2B79F5 appears exactly once",
  );

  const app = await readFile(resolve(ROOT, "public/js/app.js"), "utf8");
  check(!app.includes("innerHTML"), "app.js never uses innerHTML");
  check(!app.includes("eval(") && !app.includes("Function("), "app.js: no eval/Function");

  for (const rel of ["public/index.html", "public/en/index.html"]) {
    const html = await readFile(resolve(ROOT, rel), "utf8");
    check(html.includes('content="noindex'), `${rel}: preview noindex`);
    check(
      !/(?:src|href)\s*=\s*"https?:\/\//.test(html),
      `${rel}: no external resources`,
    );
  }
} else {
  const outDir = resolve(ROOT, "dist-preview");
  let manifest;
  try {
    manifest = JSON.parse(
      await readFile(resolve(outDir, "BUILD-MANIFEST.json"), "utf8"),
    );
  } catch {
    check(false, "dist-preview/BUILD-MANIFEST.json exists (run build:preview first)");
    process.exit(1);
  }
  const onDisk = (await listFiles(outDir)).filter(
    (f) => f !== "BUILD-MANIFEST.json",
  );
  check(
    JSON.stringify(onDisk) === JSON.stringify(manifest.files.map((f) => f.path)),
    "generated file list matches manifest",
  );
  for (const entry of manifest.files) {
    const bytes = await readFile(resolve(outDir, entry.path));
    const digest = createHash("sha256").update(bytes).digest("hex");
    check(
      digest === entry.sha256 && bytes.length === entry.bytes,
      `generated bytes match manifest: ${entry.path}`,
    );
    const srcBytes = await readFile(resolve(ROOT, "public", entry.path));
    check(
      Buffer.compare(bytes, srcBytes) === 0,
      `generated matches source: ${entry.path}`,
    );
  }
}

if (failures.length > 0) {
  console.error(`check: ${failures.length} failure(s)`);
  process.exit(1);
}
console.log("check: all passed");
