#!/usr/bin/env node
// Reproducible preview build for Stock Average Cost Calculator.
// Usage: node scripts/build.mjs --mode preview
// Copies public/ to dist-preview/ and generates dist-preview/js/
// worker-source.mjs, which embeds the fixed core bytes plus the fixed
// Worker message handler as one string. No timestamps, no network, no
// dependencies. Running the build twice produces byte-identical output.

import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const mode = argv.includes('--mode')
    ? argv[argv.indexOf('--mode') + 1]
    : 'preview';
  return { mode };
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

async function listFiles(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listFiles(full, base)));
    } else if (entry.isFile()) {
      files.push(path.relative(base, full));
    }
  }
  return files;
}

async function main() {
  const { mode } = parseArgs(process.argv.slice(2));
  if (mode !== 'preview') {
    console.error(`error: unsupported mode ${JSON.stringify(mode)} (only "preview")`);
    process.exit(1);
  }
  const outDir = path.join(root, 'dist-preview');
  const publicDir = path.join(root, 'public');

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await cp(publicDir, outDir, { recursive: true });

  const coreBytes = await readFile(path.join(root, 'public/js/core/calculate.mjs'), 'utf8');
  const handlerBytes = await readFile(path.join(root, 'scripts/worker-handler.mjs'), 'utf8');
  const workerSource = `${coreBytes}\n${handlerBytes}`;
  const workerHash = sha256(Buffer.from(workerSource, 'utf8'));
  const generated = [
    '// Generated by scripts/build.mjs --mode preview. Do not edit by hand.',
    '// Source bytes: public/js/core/calculate.mjs + scripts/worker-handler.mjs.',
    `export const WORKER_SOURCE = ${JSON.stringify(workerSource)};`,
    `export const WORKER_SOURCE_SHA256 = ${JSON.stringify(workerHash)};`,
    '',
  ].join('\n');
  await writeFile(path.join(outDir, 'js/worker-source.mjs'), generated, 'utf8');

  const files = await listFiles(outDir);
  const lines = [];
  for (const file of files) {
    const bytes = await readFile(path.join(outDir, file));
    lines.push(`${sha256(bytes)}  ${file}`);
  }
  lines.sort();
  console.log(`built dist-preview (${files.length} files)`);
  for (const line of lines) console.log(line);
}

main().catch((error) => {
  console.error(`build failed: ${error.message}`);
  process.exit(1);
});
