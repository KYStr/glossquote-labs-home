export function msg(lang, key, vars = {}) {
  const table = MESSAGES[lang] ?? MESSAGES.en;
  let text = table[key] ?? MESSAGES.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
