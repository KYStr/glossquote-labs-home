// Reproducible preview build for Log Gap Audit.
// Copies public/ to dist-preview and generates two files from the fixed
// source bytes, so the page can create its module Worker from a Blob URL:
//   dist-preview/js/worker-bundle.mjs  — core + fixed message handler
//   dist-preview/js/worker-source.mjs  — `export const WORKER_SOURCE = ...`
// Deterministic: no timestamps, no random values. Running the build twice
// produces byte-identical output.

import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const distDir = path.join(root, 'dist-preview');

const args = process.argv.slice(2);
const modeIndex = args.indexOf('--mode');
const mode = modeIndex >= 0 ? args[modeIndex + 1] : 'preview';
if (mode !== 'preview') {
  console.error(`build.mjs: unsupported --mode ${mode} (only "preview")`);
  process.exit(1);
}

async function listFiles(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(full, base)));
    else if (entry.isFile()) files.push(path.relative(base, full));
  }
  return files.sort();
}

// The worker bundle is the fixed core source followed by the fixed message
// handler fragment. The core exports stay valid in a module worker; the
// handler calls `run` from the same scope. No imports inside the bundle.
export async function buildWorkerBundle() {
  const core = await readFile(path.join(publicDir, 'js', 'core', 'audit.mjs'), 'utf8');
  const entry = await readFile(path.join(publicDir, 'js', 'worker-entry.mjs'), 'utf8');
  return (
    '// Generated by scripts/build.mjs from fixed source bytes.\n' +
    '// Do not edit: re-run `npm run build:preview`.\n' +
    core +
    '\n' +
    entry
  );
}

const bundle = await buildWorkerBundle();
if (/\bimport\s*\(|^\s*import\s+[^'"]*from/m.test(bundle)) {
  console.error('build.mjs: worker bundle must not contain imports');
  process.exit(1);
}

await rm(distDir, { recursive: true, force: true });
await mkdir(distDir, { recursive: true });
await cp(publicDir, distDir, { recursive: true });

const workerSource = `// Generated by scripts/build.mjs from fixed source bytes.\n// Do not edit: re-run \`npm run build:preview\`.\nexport const WORKER_SOURCE = ${JSON.stringify(bundle)};\n`;
await writeFile(path.join(distDir, 'js', 'worker-bundle.mjs'), bundle, 'utf8');
await writeFile(path.join(distDir, 'js', 'worker-source.mjs'), workerSource, 'utf8');

const files = await listFiles(distDir);
console.log(`build:preview: wrote ${files.length} files to dist-preview/`);
for (const file of files) console.log(`  ${file}`);
console.log(`worker bundle bytes: ${Buffer.byteLength(bundle, 'utf8')}`);
if (!existsSync(path.join(distDir, 'index.html')) || !existsSync(path.join(distDir, 'en', 'index.html'))) {
  console.error('build.mjs: missing entry pages in dist-preview');
  process.exit(1);
}
