// Verifies the generated preview output: the files in dist-preview/ must
// match BUILD-MANIFEST.json exactly (same set, same byte counts, same
// SHA-256), both generated pages must carry the preview metadata (noindex,
// language, title, description, h1, no canonical/hreflang), the embedded
// worker source must equal the fixed core + handler bytes, and robots.txt
// must deny all. Run after `npm run build:preview`.

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const DIST_ROOT = resolve(PROJECT_ROOT, "dist-preview");

const modeArg = process.argv.find((arg) => arg.startsWith("--mode"));
const mode = modeArg ? process.argv[process.argv.indexOf(modeArg) + 1] ?? modeArg.split("=")[1] : undefined;
if (mode !== "preview") {
  throw new Error("Only --mode preview is supported; production origin is not approved.");
}

async function collectFiles(directory, base = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(fullPath, base)));
    else files.push(relative(base, fullPath).split(sep).join("/"));
  }
  return files.sort();
}

const manifest = JSON.parse(await readFile(resolve(PROJECT_ROOT, "BUILD-MANIFEST.json"), "utf8"));
assert.equal(manifest.mode, "preview");
const onDisk = await collectFiles(DIST_ROOT);
assert.deepEqual(
  onDisk,
  manifest.files.map((file) => file.path).sort(),
  "dist-preview/ file set differs from BUILD-MANIFEST.json",
);
for (const file of manifest.files) {
  const bytes = await readFile(resolve(DIST_ROOT, file.path));
  assert.equal(bytes.length, file.bytes, `${file.path}: byte count`);
  assert.equal(
    createHash("sha256").update(bytes).digest("hex"),
    file.sha256,
    `${file.path}: sha256`,
  );
}

const expectations = [
  ["index.html", "zh-Hant", "重試時間預算試算"],
  ["en/index.html", "en", "Retry Time Budget Planner"],
];
for (const [path, lang, h1] of expectations) {
  const html = await readFile(resolve(DIST_ROOT, path), "utf8");
  assert.match(html, /noindex, nofollow/, `${path}: noindex`);
  assert.ok(html.includes(`<html lang="${lang}">`), `${path}: lang=${lang}`);
  assert.match(html, /<title>[^<]+<\/title>/, `${path}: title`);
  assert.match(html, /<meta name="description" content="[^"]+"/, `${path}: description`);
  assert.ok(html.includes(`<h1>${h1}</h1>`), `${path}: h1`);
  assert.ok(!html.includes("canonical"), `${path}: candidate must not carry a canonical link`);
  assert.ok(!html.includes("hreflang"), `${path}: candidate must not carry hreflang`);
}

// The embedded worker source must be exactly the fixed core + handler.
const coreSource = await readFile(resolve(PROJECT_ROOT, "public/js/core/retry.mjs"), "utf8");
const handlerSource = await readFile(resolve(PROJECT_ROOT, "public/js/worker-handler.mjs"), "utf8");
const expectedWorkerSource =
  "// Generated by scripts/build.mjs --mode preview from the fixed source\n" +
  "// bytes of public/js/core/retry.mjs and public/js/worker-handler.mjs.\n" +
  "// Do not edit by hand; rebuild to regenerate.\n" +
  `export const WORKER_SOURCE = ${JSON.stringify(`${coreSource}\n${handlerSource}`)};\n`;
const actualWorkerSource = await readFile(resolve(DIST_ROOT, "js/worker-source.js"), "utf8");
assert.equal(actualWorkerSource, expectedWorkerSource, "js/worker-source.js differs from fixed sources");

const robots = await readFile(resolve(DIST_ROOT, "robots.txt"), "utf8");
assert.equal(robots, "User-agent: *\nDisallow: /\n", "robots.txt must deny all");

console.log(
  `Generated preview verified: ${manifest.files.length} files, hashes exact, bilingual metadata present, worker source matches fixed bytes; not production`,
);
