export const messages = Object.freeze({ 'zh-Hant': zh, en });
export function errorText(language, code) { return messages[language].errors[code] ?? messages[language].errors.ZIP_FAILED; }
export function formatBytes(bytes, language) {
  const formatter = new Intl.NumberFormat(language, { maximumFractionDigits: 2 });
  if (bytes < 1024) return `${formatter.format(bytes)} B`;
  if (bytes < 1048576) return `${formatter.format(bytes / 1024)} KiB`;
  return `${formatter.format(bytes / 1048576)} MiB`;
}
